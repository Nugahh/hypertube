const dict: Record<Lang, Record<string, string>> = { en, fr };

type Vars = Record<string, string | number>;
type I18n = { lang: Lang; setLang: (l: Lang) => void; t: (key: string, vars?: Vars) => string };

const I18nContext = createContext<I18n>({ lang: "en", setLang: () => {}, t: (k) => k });
export const useI18n = () => useContext(I18nContext);

function storedLang(): Lang {
  try {
    const l = localStorage.getItem("lang");
    return LANGS.includes(l as Lang) ? (l as Lang) : "en"; // English unless the user chose otherwise
  } catch {
    return "en";
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(storedLang);
  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      localStorage.setItem("lang", lang);
    } catch {
      // storage can be blocked: the choice just won't persist
    }
  }, [lang]);
  const t = (key: string, vars: Vars = {}) =>
    (dict[lang][key] ?? dict.en[key] ?? key).replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

// the message for a failed request, in the current language
export function errorText(t: I18n["t"], e: unknown) {
  const status = (e as { status?: number }).status;
  const key = `err.${status}`;
  return dict.en[key] ? t(key) : t("err.generic", { status: status ?? "?" });
}
